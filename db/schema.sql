CREATE TABLE IF NOT EXISTS Users (
  user_id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  password_salt TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Organizations (
  org_id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Memberships (
  membership_id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL,
  org_id INTEGER NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('OWNER','ADMIN','MEMBER')) DEFAULT 'MEMBER',
  joined_at TEXT DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
  FOREIGN KEY (org_id) REFERENCES Organizations(org_id) ON DELETE CASCADE,
  UNIQUE(user_id, org_id)
);

CREATE TABLE IF NOT EXISTS Projects (
  project_id INTEGER PRIMARY KEY AUTOINCREMENT,
  org_id INTEGER NOT NULL,
  name TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (org_id) REFERENCES Organizations(org_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Tasks (
  task_id INTEGER PRIMARY KEY AUTOINCREMENT,
  project_id INTEGER NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN ('TODO','IN_PROGRESS','DONE')) DEFAULT 'TODO',
  assignee_id INTEGER,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (project_id) REFERENCES Projects(project_id) ON DELETE CASCADE,
  FOREIGN KEY (assignee_id) REFERENCES Users(user_id)
);

CREATE TABLE IF NOT EXISTS Subscriptions (
  subscription_id INTEGER PRIMARY KEY AUTOINCREMENT,
  org_id INTEGER NOT NULL UNIQUE,
  plan TEXT NOT NULL CHECK(plan IN ('FREE','PRO','ENTERPRISE')) DEFAULT 'FREE',
  status TEXT NOT NULL CHECK(status IN ('TRIALING','ACTIVE','CANCELED')) DEFAULT 'TRIALING',
  trial_ends_at TEXT,
  updated_at TEXT DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (org_id) REFERENCES Organizations(org_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Invoices (
  invoice_id INTEGER PRIMARY KEY AUTOINCREMENT,
  org_id INTEGER NOT NULL,
  plan TEXT NOT NULL,
  amount REAL NOT NULL CHECK(amount >= 0),
  status TEXT NOT NULL CHECK(status IN ('PAID','FAILED','PENDING')) DEFAULT 'PAID',
  created_at TEXT DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (org_id) REFERENCES Organizations(org_id) ON DELETE CASCADE
);
